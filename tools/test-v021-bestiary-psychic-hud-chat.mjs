const critTitle=el('Explosive critical · Leg'),critCard=el('',{'.dh2e-crit-band span':[critTitle],'.dh2e-crit-text':[criticalText]});
const root=el('',{'.dark-heresy-2e-apex-chat-card.dh2e-psychic-card':[psychicCard],'.dh2e-warp-card':[warpCard,warpCardFromPack],'.dh2e-crit-card':[critCard]});
