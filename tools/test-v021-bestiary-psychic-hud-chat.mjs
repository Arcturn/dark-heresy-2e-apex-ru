// Minimal DOM simulation: source-authored text nodes only; target names untouched.
const node=(text)=>({nodeType:3,nodeValue:text});
function el(text='',subs={}){
 const textNodes=text!==null?[node(text)]:[];
 return {nodeType:1,childNodes:textNodes,textContent:text??'',querySelector(selector){return (subs[selector]||[])[0]??null;},querySelectorAll(selector){return subs[selector]??[];},matches(){return false;}};
}
const psychicTitle=el('Smite ',{}),target=el('Player Custom Name');
